pub struct Palette {
    pub bg: u32,
    pub surface: u32,
    pub text: u32,
    pub outline: u32,
}

pub const DARK: Palette = Palette {
    bg: 0x0E0F12,
    surface: 0x15171C,
    text: 0xEDEDED,
    outline: 0xFFFFFF1F,
};
pub const OLED: Palette = Palette {
    bg: 0x000000,
    surface: 0x0A0A0A,
    text: 0xEDEDED,
    outline: 0xFFFFFF1F,
};
pub const LIGHT: Palette = Palette {
    bg: 0xF7F7F8,
    surface: 0xFFFFFF,
    text: 0x111111,
    outline: 0x00000019,
};
const PALETTES: [&Palette; 3] = [&DARK, &OLED, &LIGHT];

static ACTIVE: AtomicUsize = AtomicUsize::new(0);

pub fn palette_for(theme: Theme, appearance: WindowAppearance) -> &'static Palette {
    match theme {
        Theme::Light => &LIGHT,
        Theme::Dark => &DARK,
        Theme::Oled => &OLED,
        Theme::System => match appearance {
            WindowAppearance::Light | WindowAppearance::VibrantLight => &LIGHT,
            WindowAppearance::Dark | WindowAppearance::VibrantDark => &DARK,
        },
    }
}

pub fn apply(theme: Theme, appearance: WindowAppearance) {
    let p = palette_for(theme, appearance);
    ACTIVE.store(
        PALETTES
            .iter()
            .position(|q| std::ptr::eq(*q, p))
            .unwrap_or(0),
        Ordering::Relaxed,
    );
}

fn p() -> &'static Palette {
    PALETTES[ACTIVE.load(Ordering::Relaxed)]
}

pub fn bg() -> Rgba {
    rgb(p().bg)
}
pub fn surface() -> Rgba {
    rgb(p().surface)
}
pub fn text() -> Rgba {
    rgb(p().text)
}
pub fn muted() -> Hsla {
    Hsla::from(text()).opacity(0.6)
}
pub fn accent() -> Rgba {
    text()
}
pub fn on_accent() -> Rgba {
    bg()
}
pub fn outline() -> Rgba {
    rgba(p().outline)
}
pub fn tint(alpha: f32) -> Hsla {
    Hsla::from(text()).opacity(alpha)
}
pub fn black(alpha: f32) -> Hsla {
    Hsla::from(rgb(0x000000)).opacity(alpha)
}
pub fn white() -> Hsla {
    rgb(0xFFFFFF).into()
}
pub fn error() -> Rgba {
    rgb(0xFF8A80)
}

